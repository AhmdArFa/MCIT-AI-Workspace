import { NextResponse } from 'next/server';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';

type StudioBody = {
  format?: 'pptx' | 'pdf' | 'infograph';
  topic?: string;
};

/**
 * MCIT Studio generation endpoint.
 * Uses local Ollama when available; returns a structured draft the client can
 * display. Binary PPTX/PDF packaging can be extended without changing the API.
 */
export const POST = async (req: Request) => {
  let body: StudioBody = {};
  try {
    body = (await req.json()) as StudioBody;
  } catch {
    return NextResponse.json({ error: 'Invalid JSON body' }, { status: 400 });
  }

  const format = body.format || 'pdf';
  const topic = (body.topic || '').trim();
  if (!topic) {
    return NextResponse.json({ error: 'topic is required' }, { status: 400 });
  }
  if (!['pptx', 'pdf', 'infograph'].includes(format)) {
    return NextResponse.json({ error: 'format must be pptx | pdf | infograph' }, { status: 400 });
  }

  const ollamaBase =
    process.env.OLLAMA_PROXY_URL?.replace(/\/$/, '') ||
    process.env.OLLAMA_HOST ||
    'http://127.0.0.1:11434';
  const model = process.env.MCIT_STUDIO_MODEL || process.env.OLLAMA_CHAT_MODEL || 'gemma4:e4b';

  const system = [
    'You are MCIT Studio, an official document assistant for the Ministry of Communications and Information Technology.',
    'Write clear, professional English. Do not invent classified facts.',
    format === 'pptx'
      ? 'Output a slide outline: title + 5–8 slides with title and 3–5 bullets each.'
      : format === 'infograph'
        ? 'Output a one-page infograph structure: headline, 4–6 stat callouts, short narrative, footer note.'
        : 'Output a report: executive summary, sections with headings, recommendations, next steps.',
  ].join(' ');

  const prompt = `${system}\n\nTopic:\n${topic}`;

  try {
    const res = await fetch(`${ollamaBase}/api/generate`, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ model, prompt, stream: false }),
      signal: AbortSignal.timeout(120_000),
    });
    if (!res.ok) {
      const errText = await res.text().catch(() => '');
      return NextResponse.json(
        {
          error: `Local model unavailable (${res.status}). Configure OLLAMA_PROXY_URL and pull ${model}.`,
          detail: errText.slice(0, 400),
          format,
          content: fallbackDraft(format, topic),
        },
        { status: 200 },
      );
    }
    const data = (await res.json()) as { response?: string };
    const content = (data.response || '').trim() || fallbackDraft(format, topic);
    return NextResponse.json({
      format,
      model,
      content,
      provider: 'ollama',
    });
  } catch (e) {
    return NextResponse.json({
      format,
      model,
      provider: 'offline-fallback',
      content: fallbackDraft(format, topic),
      warning: e instanceof Error ? e.message : 'ollama unreachable',
    });
  }
};

function fallbackDraft(format: string, topic: string) {
  if (format === 'pptx') {
    return [
      `# Presentation: ${topic}`,
      '',
      '## Slide 1 — Title',
      `- ${topic}`,
      '- MCIT AI Studio',
      '',
      '## Slide 2 — Context',
      '- Background and stakeholders',
      '- Goals and constraints',
      '',
      '## Slide 3 — Key points',
      '- Point A',
      '- Point B',
      '- Point C',
      '',
      '## Slide 4 — Recommendations',
      '- Near-term actions',
      '- Owners and timelines',
      '',
      '## Slide 5 — Next steps',
      '- Decisions required',
      '- Follow-up meeting',
    ].join('\n');
  }
  if (format === 'infograph') {
    return [
      `# Infograph: ${topic}`,
      '',
      'Headline: ' + topic,
      'Callout 1: Scope',
      'Callout 2: Impact',
      'Callout 3: Timeline',
      'Callout 4: Owners',
      'Narrative: Summarize the core message for leadership in 3–4 sentences.',
      'Footer: Generated by MCIT AI Studio (local).',
    ].join('\n');
  }
  return [
    `# Report: ${topic}`,
    '',
    '## Executive summary',
    'Outline the purpose, findings, and recommended decision.',
    '',
    '## Background',
    'Describe context relevant to MCIT stakeholders.',
    '',
    '## Analysis',
    'Detail evidence, options, and trade-offs.',
    '',
    '## Recommendations',
    '1. Action one',
    '2. Action two',
    '',
    '## Next steps',
    'Owners, dates, and success criteria.',
  ].join('\n');
}
